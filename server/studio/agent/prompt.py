def _studio(caps: Capabilities) -> str:
    """What the app can do on this machine, so recommendations start from what exists (a model's tool list alone
    doesn't show it) and nothing unavailable is offered."""
    on = [text for feature, text in _TABS if feature is None or caps.features[feature].available]
    off = sorted({text.split(" (")[0] for feature, text in _TABS if feature and not caps.features[feature].available})
    missing = (f" Not available on this {caps.machine}: {', '.join(off)} (they need an NVIDIA GPU) - say so if asked "
               "and don't offer them." if off else "")
    return ("## The studio (what exists here)\n"
            f"Tabs: {', '.join(on)}. Your tools reach most of it; for the rest, point the user to the tab.{missing}\n")


